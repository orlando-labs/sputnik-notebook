import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, user: 'Alice' | 'Bob' = 'Alice') {
  await page.goto('/')
  await page.getByRole('button', { name: 'Continue with GitHub' }).click()
  await page.getByRole('button', { name: `Sign in as ${user}` }).click()
  await expect(page.getByTestId('account-name')).toHaveText(user)
}
async function snapshot(page: Page) {
  const response = await page.request.get('/api/session', { headers: { Accept: 'application/json' } })
  expect(response.status()).toBe(200)
  return response.json()
}
async function modify(page: Page, path: string, method: string, data?: unknown) {
  const csrf = (await page.context().cookies()).find(value => value.name === 'orbit-csrf')!.value
  return page.request.fetch(path, { method, data, headers: { Accept: 'application/json',
    Origin: new URL(page.url()).origin, 'X-CSRF-Token': decodeURIComponent(csrf) } })
}
async function create(page: Page, title: string) {
  const response = await modify(page, '/api/projects', 'POST', { title })
  expect(response.status()).toBe(201)
  return (await response.json()).project
}

test('anonymous shell, SSR assets, negotiation, CSRF and private API', async ({ page }) => {
  const failures: string[] = []
  const hmr: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  page.on('console', message => { if (message.type() === 'error') failures.push(message.text()) })
  page.on('websocket', socket => socket.on('framereceived', frame => {
    if (frame.payload === '{"type":"connected"}') hmr.push(socket.url())
  }))
  const response = await page.goto('/')
  await expect(page.getByRole('button', { name: 'Continue with GitHub' })).toBeVisible()
  expect(response?.headers()['cache-control']).toContain('no-store')
  expect(response?.headers()['content-security-policy']).toContain("object-src 'none'")
  expect(await response!.text()).toContain('notebook-bootstrap')
  expect((await snapshot(page)).account).toBeNull()
  expect((await page.request.get('/api/projects', { headers: { Accept: 'application/json' } })).status()).toBe(401)
  const html = await page.request.get('/projects/unknown', { headers: { Accept: 'text/html' }, maxRedirects: 0 })
  expect(html.status()).toBe(303)
  expect(html.headers().location).toBe('/')
  const incompatible = await page.request.get('/', { headers: { Accept: 'image/png' } })
  expect(incompatible.status()).toBe(406)
  expect((await page.request.post('/auth/github')).status()).toBe(403)
  const icon = await page.request.get('/favicon.svg')
  expect(icon.status()).toBe(200)
  expect(icon.headers()['content-type']).toBe('image/svg+xml')
  expect((await page.request.get('/.vite/manifest.json')).status()).toBe(404)
  if (process.env.ORBIT_E2E_MODE === 'development') await expect.poll(() => hmr.length).toBeGreaterThan(0)
  expect(failures).toEqual([])
})

