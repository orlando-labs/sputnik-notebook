async function expectNoHorizontalOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}

test('library search, details, sort, last opened, collapse and refresh', async ({ page }) => {
  await login(page)
  const prefix = `Library ${Date.now()}`
  const second = await create(page, `${prefix} 10`)
  const first = await create(page, `${prefix} 2`)
  await page.reload()
  await page.getByLabel('Sort by', { exact: true }).selectOption('name')
  await page.getByRole('button', { name: 'Open Notebook', exact: true }).click()
  const search = page.getByRole('searchbox', { name: 'Find a notebook' })
  await expect(search).toBeFocused()
  await search.fill(prefix)
  const projects = page.getByTestId('library-project')
  await expect(projects).toHaveCount(2)
  await expect(projects.nth(0)).toContainText(first.title)
  await expect(projects.nth(1)).toContainText(second.title)
  await page.getByRole('button', { name: `Show details for ${first.title}`, exact: true }).click()
  await expect(projects.nth(0)).toContainText(first.id)
  await expect(projects.nth(0)).toContainText('Not opened here yet')
  await page.getByRole('link', { name: `Open ${first.title}`, exact: true }).click()
  await expect(page.getByTestId('project-heading')).toHaveText(first.title)
  await page.getByRole('link', { name: 'Notebook Library', exact: true }).click()
  await page.getByRole('button', { name: `Show details for ${first.title}`, exact: true }).click()
  await expect(page.getByTestId('library-project').filter({ hasText: first.title })).not.toContainText('Not opened here yet')
  await page.getByLabel('Sort by', { exact: true }).selectOption('lastOpened')
  await expect(page.getByTestId('library-project').first()).toContainText(first.title)
  await page.getByRole('button', { name: 'Collapse Notebook Library' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Expand Notebook Library' })).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('button', { name: 'Open Notebook', exact: true }).click()
  await expect(search).toBeFocused()
  await search.fill('No such notebook with this name')
  await expect(page.getByRole('status')).toContainText(['No matching notebooks', '0 of'])
  await page.getByRole('button', { name: 'clear the search' }).click()
  await expect(search).toHaveValue('')
  const added = await create(page, `${prefix} added elsewhere`)
  await expect(page.getByRole('link', { name: `Open ${added.title}`, exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Refresh library' }).click()
  await expect(page.getByRole('link', { name: `Open ${added.title}`, exact: true })).toBeVisible()
  await page.getByLabel('Sort by', { exact: true }).selectOption('created')
  await page.reload()
  await expect(page.getByLabel('Sort by', { exact: true })).toHaveValue('created')
})

test('new notebook dialog handles keyboard, validation and recoverable failures', async ({ page }) => {
  await login(page)
  const open = page.getByRole('button', { name: 'New Notebook', exact: true })
  await open.click()
  const dialog = page.getByRole('dialog', { name: 'New Notebook' })
  await expect(dialog).toBeVisible()
  await expect(page.getByLabel('Notebook name')).toBeFocused()
  await page.getByLabel('Notebook name').fill('   ')
  await expect(dialog.getByRole('button', { name: 'Create Notebook', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(open).toBeFocused()
  await open.click()
  await page.getByLabel('Notebook name').fill('Recovered notebook')
  await page.route('**/api/projects', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: 'Please try again in a moment.' } }) })
  })
  await dialog.getByRole('button', { name: 'Create Notebook', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('Please try again in a moment.')
  await expect(page.getByLabel('Notebook name')).toHaveValue('Recovered notebook')
  await page.unroute('**/api/projects')
  await dialog.getByRole('button', { name: 'Create Notebook', exact: true }).click()
  await expect(page.getByTestId('project-heading')).toHaveText('Recovered notebook')
})

