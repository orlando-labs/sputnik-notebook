test('two accounts: private projects, viewer/editor ACL, owner controls and revocation', async ({ page, browser, baseURL }) => {
  await login(page)
  const project = await create(page, 'Private research')
  expect(project.role).toBe('owner')
  const other = await browser.newContext({ baseURL })
  try {
    const bob = await other.newPage()
    await login(bob, 'Bob')
    const bobId = (await snapshot(bob)).account.id
    const path = `/api/projects/${project.id}`
    expect((await snapshot(bob)).projects.some((item: any) => item.id === project.id)).toBe(false)
    expect((await bob.request.get(path, { headers: { Accept: 'application/json' } })).status()).toBe(404)
    expect((await modify(bob, path, 'PATCH', { title: 'Stolen' })).status()).toBe(404)
    expect((await modify(page, path + '/memberships', 'POST', { account_id: bobId, role: 'viewer' })).status()).toBe(200)
    const visible = await bob.request.get(path, { headers: { Accept: 'application/json' } })
    expect((await visible.json()).project.permissions).toEqual({ read: true, write: false, execute: false, manage: false })
    expect((await modify(bob, path, 'PATCH', { title: 'Viewer edit' })).status()).toBe(403)
    expect((await modify(bob, path + '/memberships', 'POST', { account_id: bobId, role: 'editor' })).status()).toBe(403)
    await bob.goto(`/projects/${project.id}`)
    await expect(bob.getByTestId('project-heading')).toHaveText('Private research')
    await expect(bob.getByRole('button', { name: 'Save title' })).toHaveCount(0)
    await expect(bob.getByRole('heading', { name: 'Project access' })).toHaveCount(0)
    expect((await modify(page, path + '/memberships', 'POST', { account_id: bobId, role: 'editor' })).status()).toBe(200)
    const renamed = await modify(bob, path, 'PATCH', { title: 'Shared edit' })
    expect(renamed.status()).toBe(200)
    expect((await renamed.json()).project.permissions.execute).toBe(true)
    expect((await modify(page, path + '/memberships', 'POST', { account_id: bobId, role: 'owner' })).status()).toBe(422)
    expect((await modify(page, path, 'PATCH', { title: '  ' })).status()).toBe(422)
    expect((await modify(page, '/api/projects', 'POST', { title: 'Injected', owner_account_id: bobId })).status()).toBe(400)
    const list = await page.request.get(path + '/memberships', { headers: { Accept: 'application/json' } })
    expect((await list.json()).memberships).toEqual([{ account_id: bobId, role: 'editor' }])
    expect((await modify(page, path + '/memberships/' + bobId, 'DELETE')).status()).toBe(204)
    expect((await bob.request.get(path, { headers: { Accept: 'application/json' } })).status()).toBe(404)
    expect((await snapshot(bob)).projects.some((item: any) => item.id === project.id)).toBe(false)
  } finally { await other.close() }
})

