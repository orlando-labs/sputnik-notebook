import Foundation

struct NotebookUnusedMedia: Identifiable, Hashable {
    let id: String
    let bytes: Int
    static func scan(project: URL, sources: String = "") throws -> [Self] {
        let manager = FileManager.default
        let root = project.standardizedFileURL.resolvingSymlinksInPath()
        let manifest = root.appendingPathComponent("project.json")
        let text = try String(contentsOf: manifest, encoding: .utf8) + sources
        var result: [Self] = []
        for folder in ["images", "audio"] {
            let directory = root.appendingPathComponent(folder)
            guard manager.fileExists(atPath: directory.path) else { continue }
            let properties = try directory.resourceValues(forKeys: [.isDirectoryKey, .isSymbolicLinkKey])
            guard properties.isDirectory == true, properties.isSymbolicLink != true else { continue }
            for file in try manager.contentsOfDirectory(at: directory, includingPropertiesForKeys: [.isRegularFileKey, .isSymbolicLinkKey, .fileSizeKey], options: [.skipsHiddenFiles]).prefix(10000) {
                let properties = try file.resourceValues(forKeys: [.isRegularFileKey, .isSymbolicLinkKey, .fileSizeKey])
                let name = file.lastPathComponent
                // Only files generated by the managed media store, never user-named files.
                guard properties.isRegularFile == true, properties.isSymbolicLink != true,
                      name.range(of: "^[0-9]+_[0-9]+_[0-9]+\\.[a-z0-9]+$", options: .regularExpression) != nil,
                      !text.contains(name) else { continue }
                result.append(.init(id: folder + "/" + name, bytes: properties.fileSize ?? 0))
            }
        }
        return result.sorted { $0.id < $1.id }
    }
    static func archive(_ selection: Set<String>, project: URL, sources: String = "") throws -> URL? {
        guard !selection.isEmpty else { return nil }
        let manager = FileManager.default
        let root = project.standardizedFileURL.resolvingSymlinksInPath()
        let current = Set(try scan(project: root, sources: sources).map(\.id))
        guard selection.isSubset(of: current) else { throw NSError(domain: "NotebookMedia", code: 1, userInfo: [NSLocalizedDescriptionKey: "Media references changed. Refresh the list before archiving."]) }
        let archiveRoot = root.appendingPathComponent(".notebook-unused")
        if manager.fileExists(atPath: archiveRoot.path) {
            let properties = try archiveRoot.resourceValues(forKeys: [.isDirectoryKey, .isSymbolicLinkKey])
            guard properties.isDirectory == true && properties.isSymbolicLink != true else { throw NSError(domain: "NotebookMedia", code: 2, userInfo: [NSLocalizedDescriptionKey: "The media archive must be a local directory."]) }
        } else { try manager.createDirectory(at: archiveRoot, withIntermediateDirectories: false) }
        let destination = archiveRoot.appendingPathComponent(UUID().uuidString)
        try manager.createDirectory(at: destination, withIntermediateDirectories: false)
        var moved: [String] = []
        do {
            for folder in ["images", "audio"] { try manager.createDirectory(at: destination.appendingPathComponent(folder), withIntermediateDirectories: false) }
            try JSONEncoder().encode(selection.sorted()).write(to: destination.appendingPathComponent("files.json"), options: .atomic)
            for relative in selection.sorted() {
                try manager.moveItem(at: root.appendingPathComponent(relative), to: destination.appendingPathComponent(relative)); moved.append(relative)
            }
        } catch {
            for relative in moved.reversed() { try? manager.moveItem(at: destination.appendingPathComponent(relative), to: root.appendingPathComponent(relative)) }
            throw error
        }
        return destination
    }
}
